import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const toolsDir = path.resolve(__dirname, "../registry/tools");
const generatedPath = path.resolve(__dirname, "../registry/generated.ts");

function toCamelCase(str) {
  return str.replace(/-([a-z0-9])/g, (_, char) => char.toUpperCase());
}

function generate() {
  if (!fs.existsSync(toolsDir)) {
    fs.mkdirSync(toolsDir, { recursive: true });
  }

  const files = fs
    .readdirSync(toolsDir)
    .filter((file) => file.endsWith(".ts"))
    .sort();

  const imports = [];
  const toolIdentifiers = [];

  for (const file of files) {
    const baseName = path.basename(file, ".ts");
    const ident = toCamelCase(baseName) + "Tool";
    imports.push(`import ${ident} from "./tools/${baseName}";`);
    toolIdentifiers.push(ident);
  }

  const output = `// AUTO-GENERATED FILE. DO NOT EDIT DIRECTLY.
// Generated by scripts/gen-registry.mjs

import { Tool } from "./types";
${imports.join("\n")}

export const allTools: Tool[] = [
  ${toolIdentifiers.join(",\n  ")}
];
`;

  fs.writeFileSync(generatedPath, output, "utf-8");
  console.log(`[gen-registry] Generated registry/generated.ts with ${files.length} tools.`);
}

generate();
